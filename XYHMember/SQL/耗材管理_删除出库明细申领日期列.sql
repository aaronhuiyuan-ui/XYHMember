/* ============================================================
   耗材出库明细：删除「申领日期」列
   库：hisdata   架构：fghis5
   ============================================================
   背景：出库登记界面的「申领日期」与「出库日期」（单据头）语义重复，
   已从界面和后端代码中移除，故删除该列。列内的值对套餐扣减单而言
   与「耗材出库单.出库日期」相同，对历史手工出库单可由
   「关联入库序号 → 耗材入库表.入库日期」还原，删除无信息损失。

   ★ 执行顺序：先把新版本程序发布上线，再执行本脚本。
     旧程序仍在 INSERT 中写 申领日期，列删掉后旧程序会报表错。

   用法：以 richhis（或更高权限）连接 172.68.1.11 / hisdata，
   选中 fghis5 执行本脚本。可重复执行。
   ============================================================ */

-- 1) 备份（仅首次执行时建表；确认无误后可自行 DROP）
IF OBJECT_ID('fghis5..耗材出库明细_申领日期备份') IS NULL
BEGIN
    SELECT 序号, 出库单号, 关联入库序号, 申领日期
    INTO fghis5..耗材出库明细_申领日期备份
    FROM fghis5..耗材出库明细;
END
GO

-- 2) 删列（幂等：列已不存在则跳过）
IF COL_LENGTH('fghis5..耗材出库明细', '申领日期') IS NOT NULL
BEGIN
    ALTER TABLE fghis5..耗材出库明细 DROP COLUMN 申领日期;
END
GO

/* ------------------------------------------------------------
   可选：回填历史出库明细的「到库日期」
   旧的出库明细当时没有自动带出到库日期，这一列都是空的。
   若要一并补齐（取该批次在耗材入库表里的入库日期），
   去掉下面这段的注释后执行。可重复执行。
   ------------------------------------------------------------
UPDATE l
SET l.到库日期 = i.入库日期
FROM fghis5..耗材出库明细 l
     JOIN fghis5..耗材入库表 i ON i.序号 = l.关联入库序号
WHERE l.到库日期 IS NULL
  AND i.入库日期 IS NOT NULL;
GO
------------------------------------------------------------ */
